const ENVIRONMENT_COMPONENT_ID_SET = new Set(ENVIRONMENT_COMPONENT_IDS);
/** @type {Set<string>} */
const CLIENT_LOGIN_TARGET_ID_SET = new Set(CLIENT_LOGIN_TARGET_IDS);
/** @type {Set<string>} */
const VALID_PREFERRED_RUNNER_SET = new Set(VALID_PREFERRED_RUNNERS);

/**
 * @param {unknown} value
 * @returns {value is EnvironmentComponentId}
 */
function isValidEnvironmentComponentId(value) {
  return typeof value === 'string' && ENVIRONMENT_COMPONENT_ID_SET.has(value);
}

/**
 * @param {unknown} value
 * @returns {value is ClientLoginTargetId}
 */
function isValidClientLoginTargetId(value) {
  return typeof value === 'string' && CLIENT_LOGIN_TARGET_ID_SET.has(value);
}

/**
 * @param {unknown} value
 * @returns {value is PreferredRunnerSelection}
 */
function isValidPreferredRunner(value) {
  return typeof value === 'string' && VALID_PREFERRED_RUNNER_SET.has(value);
}

/**
 * @param {unknown} targetId
 * @returns {ClientLoginStorefrontId | undefined}
 */
function resolveStorefrontForLoginTarget(targetId) {
  if (!isValidClientLoginTargetId(targetId)) return undefined;
  return TARGET_TO_STOREFRONT_MAP[targetId];
}

/**
 * @param {unknown} targetId
 * @returns {'host' | 'bottle' | undefined}
 */
function resolveScopeForLoginTarget(targetId) {
  if (!isValidClientLoginTargetId(targetId)) return undefined;
  return TARGET_TO_SCOPE_MAP[targetId];
}

/**
 * @param {EnvironmentComponentId} componentId
 * @param {'darwin' | 'win32' | 'linux' | string} hostPlatform
 * @returns {'host' | 'bottle' | 'system'}
 */
function resolveComponentScopeForHost(componentId, hostPlatform) {
  const entry = ENVIRONMENT_COMPONENT_CATALOG[componentId];
  if (!entry) return 'system';
  return hostPlatform === 'darwin'
    ? /** @type {'host' | 'bottle' | 'system'} */ (entry.macScope)
    : /** @type {'host' | 'bottle' | 'system'} */ (entry.winScope);
}

